import os

if os.path.exists("output/hybrid_bge_reranker_top10.json"):
    print("Saved reranked results found on Drive - skipping the reranking run.")
else:
    # T13: Re-rank the hybrid top-20 candidates with bge-reranker-large

    import json
    from tqdm.auto import tqdm

    from llama_index.postprocessor import FlagEmbeddingReranker
    from llama_index.schema import TextNode, NodeWithScore, QueryBundle

    input_file = "output/hybrid_rrf_top20_candidates.json"
    output_file = "output/hybrid_bge_reranker_top10.json"

    # Load the hybrid candidate results
    with open(input_file, "r", encoding="utf-8") as f:
        candidate_data = json.load(f)

    # Load the required BGE reranker
    reranker = FlagEmbeddingReranker(
        model="BAAI/bge-reranker-large",
        top_n=10
    )

    reranked_results = []

    for item in tqdm(candidate_data, desc="Reranking queries"):

        # Convert the saved candidate passages into LlamaIndex nodes
        nodes = [
            NodeWithScore(
                node=TextNode(text=candidate["text"]),
                score=float(candidate.get("score", 0.0))
            )
            for candidate in item["retrieval_list"]
        ]

        # Re-rank the 20 candidates for the current question
        reranked_nodes = reranker.postprocess_nodes(
            nodes,
            query_bundle=QueryBundle(query_str=item["query"])
        )

        # Save the top-10 reranked passages
        retrieval_list = []

        for node in reranked_nodes:
            retrieval_list.append(
                {
                    "text": node.node.get_content(),
                    "score": float(node.get_score())
                }
            )

        result = dict(item)
        result["retrieval_list"] = retrieval_list

        reranked_results.append(result)

    # Save all reranked results
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(
            reranked_results,
            f,
            ensure_ascii=False,
            indent=2
        )

    print("Saved reranked results to:", output_file)

