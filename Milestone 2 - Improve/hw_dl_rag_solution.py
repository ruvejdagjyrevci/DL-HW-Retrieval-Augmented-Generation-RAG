"""### 14.6 – Retrieve with the original question vs. with sub-questions (hybrid RRF)

We build two candidate pools of the **same size** (20 chunks) for every question:

| Pool | Ranked lists fused with RRF |
|---|---|
| **Original** (T14 baseline) | dense(question), BM25(question) |
| **Decomposed** | dense(question), BM25(question) **+** dense(sub-q), BM25(sub-q) for every sub-question |

**Reciprocal Rank Fusion (RRF):** a chunk at rank *r* in a list gets 1/(60 + r) points, and the points from all lists are added together. A chunk that appears high in several lists wins. This is the same method and constant (k = 60) as in T12/T13.

**Why the same pool size?** If the decomposed pool were bigger, it could look better just because it has more chunks. With equal pool sizes, the **only** difference between the two runs is how the queries were written.

We keep the original question in the decomposed pool as a safety net, in case the LLM writes a bad sub-question.
"""

# T14.6: Hybrid RRF pools for original vs. decomposed queries

def rrf_fuse(ranked_lists, k_rrf=RRF_K, top=POOL):
    scores = defaultdict(float)
    for lst in ranked_lists:
        for rank, c in enumerate(lst):
            scores[c] += 1.0 / (k_rrf + rank + 1)
    best = sorted(scores, key=scores.get, reverse=True)[:top]
    return best, [scores[c] for c in best]

# Retrieve for all sub-questions in one go (flattened list + mapping back to the question)
