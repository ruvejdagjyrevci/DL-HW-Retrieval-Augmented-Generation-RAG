for j, i in enumerate(owner):
    lists_per_question[i] += [sub_dense[j], sub_bm25[j]]

orig_pool, decomp_pool = [], []
for i in range(len(questions)):
    orig_pool.append(rrf_fuse([orig_dense[i], orig_bm25[i]]))
    decomp_pool.append(rrf_fuse([orig_dense[i], orig_bm25[i]] + lists_per_question[i]))

