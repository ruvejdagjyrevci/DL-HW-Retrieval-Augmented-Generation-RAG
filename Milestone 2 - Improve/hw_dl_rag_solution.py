"""### 14.2 – Load the chunks and build our own dense and BM25 retrievers

To test question decomposition, we have to retrieve evidence for **new** queries (the sub-questions). Calling the repository scripts thousands of times would be very slow: dense retrieval took about 25 minutes for 2,556 queries in T8.

So we build two fast retrievers over **the same 8,034 chunks** from the Milestone 1 index:

- **Dense:** we re-use the chunk embeddings stored in the Milestone 1 index (`bge-large-en-v1.5`). A query is embedded once, and its similarity to all chunks is a single matrix multiplication on the GPU.
- **BM25:** the Okapi BM25 formula (k1 = 1.5, b = 0.75, as in `rank_bm25`), written as one sparse matrix. Scoring many queries is then a single matrix product.

Each chunk text keeps its header (title, source, publication date), as in Milestone 1.

**Sanity check:** before trusting these retrievers, we run them on the original questions and compare with the Milestone 1 numbers. They should be close but not identical, because the tokenization and the query instruction differ slightly.
"""

# T14.2: Load the 8,034 chunks of the Milestone 1 index and build dense + BM25 retrievers

from llama_index import StorageContext
from llama_index.schema import MetadataMode
from sentence_transformers import SentenceTransformer
from sklearn.feature_extraction.text import CountVectorizer
import scipy.sparse as sp

t0 = time.perf_counter()
storage = StorageContext.from_defaults(persist_dir=PERSIST_DIR)
node_dict = storage.docstore.docs
node_ids = list(node_dict.keys())

# Text used by BM25, the reranker and the LLM: header (title / source / date) + chunk text
chunk_texts = [node_dict[n].get_content(metadata_mode=MetadataMode.LLM) for n in node_ids]
print("Number of chunks:", len(chunk_texts))
print("\nExample chunk:\n", chunk_texts[0][:500])

# ---- Dense retriever ----
embedder = SentenceTransformer(EMBED_MODEL, device="cuda")
embedder.half()   # fp16 -> faster on the T4

try:
    chunk_emb = np.array([storage.vector_store.get(n) for n in node_ids], dtype=np.float32)
    print("\nRe-using the chunk embeddings stored in the Milestone 1 index.")
except Exception as e:
    print("\nStored embeddings not available (", repr(e), ") -> computing them again ...")
    embed_texts = [node_dict[n].get_content(metadata_mode=MetadataMode.EMBED) for n in node_ids]
    chunk_emb = embedder.encode(embed_texts, batch_size=64, normalize_embeddings=True,
                                show_progress_bar=True, convert_to_numpy=True)

chunk_emb = chunk_emb / np.linalg.norm(chunk_emb, axis=1, keepdims=True)   # cosine similarity
chunk_emb_t = torch.tensor(chunk_emb, device="cuda", dtype=torch.float16)

# BGE models expect this instruction in front of a search query (LlamaIndex adds the same one)
QUERY_INSTRUCTION = "Represent this question for searching relevant passages: "

def dense_search(queries, k=POOL, batch=1024):
    """Return, for every query, the indices of the k most similar chunks."""
    results = []
    for s in range(0, len(queries), batch):
        q = embedder.encode([QUERY_INSTRUCTION + x for x in queries[s:s + batch]],
                            batch_size=64, normalize_embeddings=True, convert_to_tensor=True)
        scores = q.half() @ chunk_emb_t.T
        top = torch.topk(scores, k, dim=1).indices.cpu().numpy()
        results += [row.tolist() for row in top]
    return results

# ---- BM25 retriever (Okapi BM25 as one sparse matrix) ----
vectorizer = CountVectorizer(lowercase=True, token_pattern=r"(?u)\b\w+\b")
tf = vectorizer.fit_transform(chunk_texts).tocsr().astype(np.float32)   # chunks x words (counts)
N = tf.shape[0]
doc_len = np.asarray(tf.sum(axis=1)).ravel()
avgdl = doc_len.mean()
df = np.bincount(tf.indices, minlength=tf.shape[1])          # in how many chunks each word appears
idf = np.log(1 + (N - df + 0.5) / (df + 0.5))
K1, B = 1.5, 0.75
row_of_value = np.repeat(np.arange(N), np.diff(tf.indptr))
weights = idf[tf.indices] * tf.data * (K1 + 1) / (tf.data + K1 * (1 - B + B * doc_len[row_of_value] / avgdl))
bm25_matrix = sp.csr_matrix((weights, tf.indices, tf.indptr), shape=tf.shape)

def bm25_search(queries, k=POOL, batch=512):
    """BM25 score(query, chunk) = sum of the chunk's BM25 weights for the query words."""
    results = []
    for s in range(0, len(queries), batch):
        q = vectorizer.transform(queries[s:s + batch])          # word counts of each query
        scores = (q @ bm25_matrix.T).toarray()                 # queries x chunks
        top = np.argsort(-scores, axis=1)[:, :k]
        results += [row.tolist() for row in top]
    return results

