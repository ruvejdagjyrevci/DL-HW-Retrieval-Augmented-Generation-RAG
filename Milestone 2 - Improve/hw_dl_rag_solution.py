"""### 15.3 – How we score the answers

**Accuracy:** an answer is correct if the gold answer appears in the model's first line as a whole word or phrase, after lower-casing and removing punctuation. For example, gold "Yes" matches the prediction "Yes." but not "Yesterday".

For the hallucination question we also measure:
- **Null: abstained:** on the null questions (no answer exists in the corpus), how often the model correctly says *Insufficient information*. Higher is better.
- **Answerable: wrongly abstained:** on answerable questions, how often the model gives up although an answer exists. Lower is better.

These two numbers pull against each other. A model that always says "I don't know" gets 100% on the first and fails the second. Milestone 3 studies this trade-off in detail.

*Limitation:* string matching can mark a correct answer as wrong, for example "Bankman-Fried" vs. gold "Sam Bankman-Fried". Milestone 3 compares this metric with manual checks and an LLM judge.
"""

# T15.3: Answer scoring

def normalize(text):
    text = re.sub(r"[^\w\s]", " ", text.lower())
    return " ".join(text.split())

def is_abstention(pred):
    return "insufficient information" in normalize(pred)

def is_correct(pred, gold):
    g = normalize(gold)
    if g == "insufficient information":          # null question: correct = the model abstains
        return is_abstention(pred)
    if is_abstention(pred):
        return False
    lines = pred.strip().split("\n")
    p = normalize(lines[0]) if lines else ""
    return p == g or re.search(r"\b" + re.escape(g) + r"\b", p) is not None

def answer_metrics(preds, split):
    ids = splits[split]
    answerable = [i for i in ids if questions[i]["question_type"] != "null_query"]
    nulls = [i for i in ids if questions[i]["question_type"] == "null_query"]
    m = {
        "Acc (all)":        np.mean([is_correct(preds[i], questions[i]["answer"]) for i in ids]),
        "Acc (answerable)": np.mean([is_correct(preds[i], questions[i]["answer"]) for i in answerable]),
    }
    for t in QTYPES:
        t_ids = [i for i in ids if questions[i]["question_type"] == t]
        m[f"Acc {t.split('_')[0]}"] = np.mean([is_correct(preds[i], questions[i]["answer"]) for i in t_ids])
    m["Null: abstained"] = np.mean([is_abstention(preds[i]) for i in nulls])
    m["Answerable: wrongly abstained"] = np.mean([is_abstention(preds[i]) for i in answerable])
    return {k: float(v) for k, v in m.items()}

