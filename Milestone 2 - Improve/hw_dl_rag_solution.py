"""### 14.3 – Load a small open LLM in 4-bit precision

We use **Qwen2.5-3B-Instruct** for two jobs: splitting questions here in T14, and answering them in T15.

**What is 4-bit?** Normally each model weight is stored with 16 bits. With 4-bit quantization (`bitsandbytes`, NF4 format), each weight uses only 4 bits, so the model needs about 4 times less GPU memory. A 3-billion-parameter model then fits in about 2–3 GB, which is easy on a free Colab T4. The price is a small loss in quality and somewhat slower generation.

Two helper functions are defined here and re-used in T15:
- `generate_batch()` generates text for several prompts at once. Batching is much faster than one prompt at a time.
- `run_cached()` saves the answers to a file after **every** batch. If Colab disconnects, re-running the cell continues where it stopped instead of starting again.

We use **greedy decoding** (`do_sample=False`), so the outputs are deterministic and reproducible.
"""

# T14.3: Load Qwen2.5-3B-Instruct in 4-bit and define generation helpers (also used in T15)

from transformers import AutoTokenizer, AutoModelForCausalLM, BitsAndBytesConfig

t0 = time.perf_counter()
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",              # 4-bit "NormalFloat" format
    bnb_4bit_compute_dtype=torch.float16,   # calculations are done in fp16
    bnb_4bit_use_double_quant=True,         # saves a little more memory
)
tokenizer = AutoTokenizer.from_pretrained(LLM_NAME)
tokenizer.padding_side = "left"             # required for batched generation with decoder-only models
llm = AutoModelForCausalLM.from_pretrained(LLM_NAME, quantization_config=bnb_config, device_map="auto")
llm.eval()
timings["T14 load 4-bit LLM"] = time.perf_counter() - t0

print(f"LLM memory footprint: {llm.get_memory_footprint() / 1e9:.2f} GB")
print(f"GPU memory allocated in total: {torch.cuda.memory_allocated() / 1e9:.2f} GB")

PAD_ID = tokenizer.pad_token_id if tokenizer.pad_token_id is not None else tokenizer.eos_token_id

def chat_prompt(messages):
    """Turn a list of chat messages into the text format the model was trained on."""
    return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)

@torch.no_grad()
def generate_batch(prompts, max_new_tokens):
    enc = tokenizer(prompts, return_tensors="pt", padding=True).to(llm.device)
    out = llm.generate(**enc, max_new_tokens=max_new_tokens, do_sample=False, pad_token_id=PAD_ID)
    new_tokens = out[:, enc["input_ids"].shape[1]:]          # keep only the generated part
    return tokenizer.batch_decode(new_tokens, skip_special_tokens=True)

def run_cached(prompts, cache_path, max_new_tokens, batch_size=16, desc=""):
    """prompts: {question_index: prompt}.  Returns {question_index: generated text}.
    Saves after every batch, so an interrupted run can be resumed."""
    cache = {}
    if os.path.exists(cache_path):
        with open(cache_path) as f:
            cache = {int(k): v for k, v in json.load(f).items()}
    todo = [i for i in prompts if i not in cache]
    todo.sort(key=lambda i: len(prompts[i]))                 # similar lengths together -> less padding
    print(f"{desc}: {len(prompts) - len(todo)} cached, {len(todo)} to generate")
    for s in tqdm(range(0, len(todo), batch_size), desc=desc):
        batch = todo[s:s + batch_size]
        for i, text in zip(batch, generate_batch([prompts[i] for i in batch], max_new_tokens)):
            cache[i] = text.strip()
        with open(cache_path, "w") as f:
            json.dump(cache, f)
    return {i: cache[i] for i in prompts}

